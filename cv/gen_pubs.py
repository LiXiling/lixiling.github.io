"""Generate cv/pubs.tex from ../publications.html, so the website stays the
single source of truth for papers. Run from anywhere: python3 cv/gen_pubs.py

Each paper becomes  \\Pub{id}{group}{badge}{title}{authors}{venue}{year}{url}
where group is conference | journal | preprint | workshop. The CV designs
decide how to typeset it and which ids to show (see SELECTED in content.tex).
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT.parent / "publications.html"
OUT = ROOT / "pubs.tex"

ME = {"Maximilian Xiling Li", "Maximilian Li", "Maximilian X. Li"}
JOURNALS = {"MISQ", "TKL", "IEEE TAC", "KI"}
TEX_ESCAPES = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
               "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def text(fragment):
    """HTML fragment -> plain text."""
    return html.unescape(re.sub(r"<[^>]+>", "", fragment)).strip()


def tex(s):
    s = "".join(TEX_ESCAPES.get(c, c) for c in s)
    return s


def main():
    page = SRC.read_text(encoding="utf-8")
    entries = re.findall(r'<li class="pub" id="([\w-]+)" data-year="(\d+)" data-venue="([^"]+)">(.*?)</li>', page, re.S)
    lines = ["% Generated by gen_pubs.py from publications.html — do not edit by hand.", ""]
    for pid, year, venue_key, body in entries:
        url = html.unescape(re.search(r'<h3><a href="([^"]+)"', body).group(1))
        title = text(re.search(r"<h3>(.*?)</h3>", body, re.S).group(1))
        authors = [a.strip() for a in text(re.search(r'<p class="authors">(.*?)</p>', body, re.S).group(1)).split(",")]
        venue = text(re.search(r'<span class="venue-full">(.*?)</span>', body, re.S).group(1))
        venue = re.sub(r",\s*\d{4}$", "", venue)  # year is its own field
        if venue_key == "Preprint":
            group, badge = "preprint", "Preprint"
        elif venue_key == "Workshop":
            group, badge = "workshop", "Workshop"
        else:
            group, badge = ("journal" if venue_key in JOURNALS else "conference"), venue_key
        author_tex = ", ".join(rf"\Me{{{tex(a)}}}" if a in ME else tex(a) for a in authors)
        lines.append(rf"\Pub{{{pid}}}{{{group}}}{{{tex(badge)}}}{{{tex(title)}}}{{{author_tex}}}{{{tex(venue)}}}{{{year}}}{{{url}}}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} papers to {OUT.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
